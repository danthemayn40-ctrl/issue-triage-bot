import * as core from '@actions/core';
import * as github from '@actions/github';
import * as yaml from 'js-yaml';
import { promises as fs } from 'fs';

interface Config {
  labels: Record<string, { keywords: string[]; color: string }>;
  priority?: {
    keywords: Record<string, string[]>;
  };
}

async function run() {
  try {
    const token = core.getInput('github-token', { required: true });
    const configPath = core.getInput('config-path');
    const enableSummary = core.getInput('enable-summary') === 'true';
    const enableDuplicateDetection = core.getInput('enable-duplicate-detection') === 'true';

    const octokit = github.getOctokit(token);
    const context = github.context;

    if (context.eventName !== 'issues' && context.eventName !== 'pull_request') {
      core.setFailed('This action only runs on issues or pull_request events');
      return;
    }

    const issue = context.payload.issue || context.payload.pull_request;
    if (!issue) {
      core.setFailed('No issue or pull request found in payload');
      return;
    }

    // Load config
    let config: Config = { labels: {} };
    try {
      const configFile = await fs.readFile(configPath, 'utf8');
      config = yaml.load(configFile) as Config;
    } catch (error) {
      core.warning(`Could not load config from ${configPath}, using defaults`);
    }

    const title = issue.title.toLowerCase();
    const body = (issue.body || '').toLowerCase();
    const content = `${title} ${body}`;

    const labelsToAdd: string[] = [];

    // Auto-label based on keywords
    for (const [labelName, labelConfig] of Object.entries(config.labels)) {
      for (const keyword of labelConfig.keywords) {
        if (content.includes(keyword.toLowerCase())) {
          if (!labelsToAdd.includes(labelName)) {
            labelsToAdd.push(labelName);
          }
          break;
        }
      }
    }

    // Detect priority
    if (config.priority) {
      for (const [priority, keywords] of Object.entries(config.priority.keywords)) {
        for (const keyword of keywords) {
          if (content.includes(keyword.toLowerCase())) {
            const priorityLabel = `priority: ${priority}`;
            if (!labelsToAdd.includes(priorityLabel)) {
              labelsToAdd.push(priorityLabel);
            }
            break;
          }
        }
      }
    }

    // Add triaged label
    if (labelsToAdd.length > 0 && !labelsToAdd.includes('triaged')) {
      labelsToAdd.push('triaged');
    }

    // Apply labels
    if (labelsToAdd.length > 0) {
      await octokit.rest.issues.addLabels({
        owner: context.repo.owner,
        repo: context.repo.repo,
        issue_number: issue.number,
        labels: labelsToAdd,
      });
      core.info(`Added labels: ${labelsToAdd.join(', ')}`);
    }

    // Add summary comment if enabled
    if (enableSummary && issue.body && issue.body.length > 200) {
      const summary = generateSummary(issue.title, issue.body);
      await octokit.rest.issues.createComment({
        owner: context.repo.owner,
        repo: context.repo.repo,
        issue_number: issue.number,
        body: `## 🤖 Auto-Triage Summary\n\n${summary}\n\n---\n*This was automatically generated by [Issue Triage Bot](https://github.com/danthemayn40-ctrl/issue-triage-bot).*`,
      });
      core.info('Added summary comment');
    }

    // Duplicate detection if enabled
    if (enableDuplicateDetection) {
      await detectDuplicates(octokit, context, issue);
    }

  } catch (error) {
    if (error instanceof Error) {
      core.setFailed(error.message);
    }
  }
}

function generateSummary(title: string, body: string): string {
  // Simple extractive summary - take first few sentences
  const sentences = body.split(/[.!?]+/).filter(s => s.trim().length > 10);
  const summary = sentences.slice(0, 3).join('. ').trim() + '.';
  return `**Issue:** ${title}\n\n**Summary:** ${summary}`;
}

async function detectDuplicates(octokit: any, context: any, issue: any) {
  try {
    // Search for similar issues
    const { data: issues } = await octokit.rest.issues.listForRepo({
      owner: context.repo.owner,
      repo: context.repo.repo,
      state: 'open',
      per_page: 30,
    });

    const titleWords = issue.title.toLowerCase().split(/\W+/).filter((w: string) => w.length > 3);
    const similarIssues = issues.filter((existingIssue: any) => {
      if (existingIssue.number === issue.number) return false;
      const existingWords = existingIssue.title.toLowerCase().split(/\W+/).filter((w: string) => w.length > 3);
      const commonWords = titleWords.filter((w: string) => existingWords.includes(w));
      return commonWords.length >= 2;
    });

    if (similarIssues.length > 0) {
      const duplicatesList = similarIssues.slice(0, 3).map((i: any) => `- #${i.number}: ${i.title}`).join('\n');
      await octokit.rest.issues.createComment({
        owner: context.repo.owner,
        repo: context.repo.repo,
        issue_number: issue.number,
        body: `## 🔍 Potential Duplicates\n\nThis issue might be related to:\n\n${duplicatesList}\n\nPlease check if any of these are duplicates before proceeding.\n\n---\n*This was automatically generated by [Issue Triage Bot](https://github.com/danthemayn40-ctrl/issue-triage-bot).*`,
      });
      core.info('Added duplicate detection comment');
    }
  } catch (error) {
    core.warning('Could not perform duplicate detection');
  }
}

run();
